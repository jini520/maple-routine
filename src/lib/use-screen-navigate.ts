import { useCallback } from 'react'
import { useNavigate } from 'react-router-dom'

// 화면을 통째로 바꾸는 이동 — 스크롤을 최상단으로 옮기고 **같은 태스크에서** 이동한다([[ADR-098]] 결정 1).
//
// 네 탭 화면은 문서 전체 스크롤 하나를 공유한다([[ADR-072]] 결정 1 — 화면별 스크롤 컨테이너가 없다).
// 그대로 이동하면 새 화면이 옛 화면의 오프셋으로 마운트되고, 문서 높이가 다르면 브라우저가 그
// 오프셋을 잘라낸다(계측 2026-08-06: 보스 y=649 doc 1432 → 컨텐츠 y=289 doc 1072). 그 클램프에
// iOS 스크롤 스레드가 뒤늦게 되돌려 보내는 옛 오프셋([[ADR-085]] 실기기 계측)이 겹치면 한 프레임이
// 무효 오프셋으로 그려진다. 문서가 아직 높을 때 0으로 옮겨두면 잘라낼 것이 없다.
//
// **두 일을 한 태스크 안에서 끝내는 것이 핵심이다.** `requestAnimationFrame` 으로 이동을 한 프레임
// 미뤘더니 그 프레임에 **떠나는 화면이 최상단으로 올라간 모습이 실기기에서 그대로 보였다**
// (2026-08-06 연속 프레임 촬영, 사용자 반려 — [[ADR-098]] 폐기 1). 스크롤과 DOM 교체 사이에 페인트가
// 없으면 그 중간 상태는 화면에 나오지 않는다. **`rAF`·`setTimeout` 으로 이동을 미루지 말 것.**
//
// 마운트 후에 고치는 처방도 안 된다 — 그때는 이미 클램프가 끝나 있다([[ADR-084]] 실기기 반증).
//
// 목적지가 0인 것도 선택이 아니다 — 새 화면의 높이는 이동 전에 알 수 없어 유효한 다른 값이 없고,
// 0은 [[ADR-082]] 폐기가 확인한 대로 헤더의 자연 위치다.
//
// **예외는 `/profit/drops` 오버레이**([[ADR-077]]) — 자기 스크롤 컨테이너를 갖고, 돌아왔을 때 보스
// 수익의 스크롤이 유지되는 것이 그 ADR 의 계약이라 그 왕복은 평범한 `useNavigate` 를 쓴다.
export function useScreenNavigate(): (to: string) => void {
  const navigate = useNavigate()

  return useCallback(
    (to: string) => {
      window.scrollTo(0, 0)
      navigate(to)
    },
    [navigate],
  )
}
