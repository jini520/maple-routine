import { View } from 'react-native'

import { useTopSafeAreaPx } from '../../../lib/safe-area'


// 화면 상단 헤더 셸(4단계). 스케줄러 계열 4화면이 **글자 하나까지 같은** 마크업을
// 복붙하고 있었다. 셸 클래스, 테마 배경 조각, 하단 페이드까지. 취약 구조를 한곳에 가두는 것이
// 목적이고, 그 취약함의 내용이 RN 에서 통째로 바뀐다.
// ── 안전영역 ─────────────────────────────────────────────────────────────────────
//
// `pt-[calc(1rem+var(--sa-top))]` → `paddingTop: 상단 안전영역`. 값의 출처가 CSS 변수 주입에서
// `SafeAreaProvider` 로 바뀔 뿐 뜻은 같다(그래서 `SystemBarsPort.refreshSafeAreaInsets()` 가 RN 에서
// 할 일이 없다. `native/adapters/rn-system-bars.ts`). **헤더가 상단 안전영역을 먹는 쪽이라는
// 사실이 계약이다**. `ScreenScroll` 은 헤더가 있으면 그 위쪽을 건드리지 않는다.
//
// 그 값은 `insets.top` 이 **아니라** `useTopSafeAreaPx()` 다. 안드로이드에서만
// 하한 48 이 깔린다(실기기 인셋 31.3 은 iOS 59 의 절반이 안 돼 **여백이 부족** 했다). 하한을 이
// 헤더가 아니라 **안전영역 값 쪽에** 단 이유는 바로 아래 문단이다.
//
  // **상수 몫 `1rem` 은 옮기지 않는다**(사용자 판정 2026-08-16). 그 16 이 하던
// 일은 둘인데 여기서는 둘 다 없다. ① 불투명 헤더 판의 안쪽 여백(RN 헤더는 자기 배경을 안 칠한다,
//) ② 고정된 헤더와 상태바의 시각적 분리(RN 헤더는 고정이 아니다. 굴리면
// 상태바 밑으로 지나가고 그 자리는 페이드가 깎는다).
//
// 그래서 **제목 윗변과 그 페이드의 끝선이 같은 선**이 됐다. 지금은 마스크 알파가 그 선에서 1 이라
// (smoothstep² 은 양 끝 기울기가 0 이다) 제목이 불투명하지만 **여유가 0** 이다. 페이드 길이
// (`safe-area-fade.ts`)를 늘리면 제목 윗변부터 갉힌다. 두 값이 이제 서로를 본다.
//
// **그래서 안드로이드 하한이 여기가 아니라 `lib/safe-area.ts` 에 있다**.
// 이 헤더에만 더하면 제목은 내려가는데 페이드는 짧은 채로 남아 **그 선이 갈라진다**. 결정 1 이
// 대가를 치르고 얻은 성질을 그대로 버리는 셈이다. 밑에 깔면 둘이 계속 같은 값을 본다.
//
// ── 보스 수익은 여전히 여기 포함하지 않는다 ────────────────────────────────────────
//
// 같은 형태지만 페이지 헤더에 경계 페이드를 두지 않는다. 헤드라인 실측을 중첩
// sticky 레일에 쓰던 **쓰임 쪽이 없어졌다**. 이 그 레일과 `stickyTop` 오프셋
// 을 통째로 폐기했다. 남는 이유는 **페이드가 없다** 하나다.

export interface PageHeaderProps {
  /** 헤더 내용. 안에서 `gap-4` 로 세로 간격이 잡힌다. */
  children: React.ReactNode
  /**
   * 헤더 **바로 아래 띠**(`top-full`)에 겹쳐 그릴 것. 현재는 당겨서 새로고침 인디케이터
   * 하나다(스케줄러 2화면).
   *
 * 프롭으로 받는다. 그 인디케이터는 `absolute inset-x-0 top-full` 이라 **이 셸이
   * 기준 상자여야** 한다. `children` 에 섞으면 `gap-4` 안으로 들어가 흐름 자식이 되어 위치가
   * 완전히 달라진다.
   */
  below?: React.ReactNode
}

export function PageHeader(props: PageHeaderProps): React.JSX.Element {
  const topSafeAreaPx = useTopSafeAreaPx()

  return (
    <View testID="page-header" className="z-10 px-4 pb-2" style={{ paddingTop: topSafeAreaPx }}>

      <View className="gap-4">{props.children}</View>

      {/* **경계 페이드를 걷어냈다**(2026-08-13, 사용자 판정. 실기기에서 **띠가 엉뚱한 자리에
          있다**, 제거 승인).

          웹에서 이 띠는 헤더 아래 32px 에 겹쳐 그려 목록이 경계에서 딱 끊기지 않게 하는 것이었다.
          RN 에서 그 자리를 `absolute … top-full h-8` 로 옮겼는데, 그 배치는 **부모(헤더) 높이를
          기준으로 100% 아래**를 뜻하므로 헤더가 스크롤에 맞춰 높이를 바꾸는 자리에서는 띠가 함께
          움직여 의도한 경계와 어긋난다.

          위치를 고치는 대신 없앤 이유: 이 띠는 이 **페이지 헤더에는 두지
          않기로** 한 것과 같은 부류의 장식이고(이 블러를 걷어낸 것도 같은 방향),
          지금은 의 중첩 sticky 자체가 RN 에 없어 이 띠가 덮어 줄 경계도 없다.
          **되살릴 조건이던 sticky 를 먼저 세운다 는 영영 성립하지 않는다**. 이
          화면에 고정되는 영역을 두지 않기로 정했고, 헤더까지 함께 스크롤되면 **헤더 아래로
          콘텐츠가 지나가는 경계** 자체가 없다. 조건부 보류가 아니라 확정 폐기다.

          되살릴 때 필요한 값(알파 **(1−t)²** 프로파일 · 정지점이 전부 테마 `bg` 의 알파 변주 ·
          블러 금지)은 **웹 원본**(`app-capacitor` 의 같은 헤더)에 그대로 있다. 여기
          상수로 남겨 두지 않는 이유는 쓰는 데가 없는 값이 lint 를 깨고, 그 상태로 두면 다음
          사람이 "왜 있는데 안 쓰지"를 먼저 풀어야 하기 때문이다. */}

      {props.below}
    </View>
  )
}
