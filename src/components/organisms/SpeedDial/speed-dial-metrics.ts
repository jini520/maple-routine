/**
 * 다이얼의 **치수** — 가 예고한 결함의 처방이다.
 *
 * > *"딸려 오는 결함 하나 — 접힌 FAB 가 6주 달의 마지막 줄을 가린다. 처방은 `ScreenScroll` 하단에
 * > FAB 높이 + 여백만큼 패딩을 주는 것."*
 *
 * FAB 는 **화면 위에 떠 있어 콘텐츠를 밀어내지 않는다.** 그래서 스크롤을 끝까지 내리면 마지막 줄이
 * 버튼 뒤로 들어간다 — 실제로 그랬다(사용자 보고 2026-08-25: *"제일 아래쪽에 있는 리스트가 안보여"*).
 *  로 그날 목록이 길어지면서 가리는 대상이 격자에서 목록으로 옮겨간 것뿐이고, 결함은
 * 처음부터 같은 것이다.
 *
 * ## 왜 값이 파일로 나와 있나
 *
 * 이 숫자를 **두 곳이 나눠 쓴다** — 다이얼이 자기 높이를 정하고, 화면이 그만큼을 콘텐츠 끝에
 * 갚는다. 한쪽에 손으로 옮겨 적으면 갈리고, 갈리면 **화면에서는 **조금 가린다** 로만 보인다**
 * (`SpeedDial` 이 자기 `bottom` 을 `bottom-inset.ts` 와 같은 함수에서 얻는 것과 같은 이유).
 *
 * 하단바의 몫(`bottomSafeAreaPx + barSpacePx`)은 **여기 없다.** 그것은 `ScreenScroll` 이 이미 콘텐츠
 * 끝에 남기고 있고, 다이얼은 그 위에 앉는다 — 화면이 갚아야 하는 것은
 * **그 위로 더 먹는 몫**뿐이다. 창 폭에 따라 달라지는 값도 여기 없다(바 높이만 그렇다).
 */

/** FAB 의 지름. `SpeedDial` 의 `h-14 w-14` 와 같아야 하고, 그 약속은 테스트가 잰다. */
export const FAB_DIAMETER_PX = 56

/** FAB 가 하단바 위로 뜨는 높이. */
export const FAB_LIFT_PX = 12

/**
 * 마지막 줄과 FAB 사이의 **숨돌림**.
 *
 * 0 이면 안 가린다 는 만족하지만 마지막 줄이 버튼에 딱 붙는다. 화면의 리듬과 같은 16 을 쓴다 —
 * 이 값이 화면의 `pb-4` 를 대신하므로, 넣지 않으면 바닥 여백이 도리어 사라진다.
 */
export const FAB_CONTENT_GAP_PX = 16

/**
 * 다이얼이 하단바 **위로 더 먹는** 세로 몫 — 스크롤 콘텐츠가 끝에 남겨야 하는 값이다.
 *
 * 화면의 `pb-4` 를 **대신한다**(더하지 않는다) — 둘을 더하면 바닥 여백이 두 번 붙는다.
 */
export const SPEED_DIAL_SPACE_PX = FAB_LIFT_PX + FAB_DIAMETER_PX + FAB_CONTENT_GAP_PX
