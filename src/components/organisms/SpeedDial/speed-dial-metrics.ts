/**
 * 펼침판의 치수. 화면이 콘텐츠 끝에 갚아야 할 높이를 함께 내는 값.
 *
 * FAB 는 화면 위에 떠 있어 콘텐츠를 밀어내지 않는다. 그래서 스크롤을 끝까지 내리면 마지막 줄이
 * 버튼 뒤로 들어간다(사용자 보고).
 *
 * **값이 파일로 나와 있는 것은 두 곳이 나눠 쓰기 때문이다.** 다이얼이 자기 높이를 정하고 화면이
 * 그만큼을 콘텐츠 끝에 갚는다. 한쪽에 손으로 옮겨 적으면 갈리고, 갈려도 화면에서는 조금 가린다로만
 * 보인다.
 *
 * 하단바의 몫은 여기 없다. `ScreenScroll` 이 이미 콘텐츠 끝에 준다.
 */

/** FAB 의 지름. `SpeedDial` 의 `h-14 w-14` 와 같아야 하고, 그 약속은 테스트가 잰다. */
export const FAB_DIAMETER_PX = 56

/** FAB 가 하단바 위로 뜨는 높이. */
export const FAB_LIFT_PX = 12

/**
 * 마지막 줄과 FAB 사이의 **숨돌림**.
 *
 * 0 이면 안 가린다 는 만족하지만 마지막 줄이 버튼에 딱 붙는다. 화면의 리듬과 같은 16 을 쓴다.
 * 이 값이 화면의 `pb-4` 를 대신하므로, 넣지 않으면 바닥 여백이 도리어 사라진다.
 */
export const FAB_CONTENT_GAP_PX = 16

/**
 * 다이얼이 하단바 **위로 더 먹는** 세로 몫. 스크롤 콘텐츠가 끝에 남겨야 하는 값이다.
 *
 * 화면의 `pb-4` 를 **대신한다**(더하지 않는다). 둘을 더하면 바닥 여백이 두 번 붙는다.
 */
export const SPEED_DIAL_SPACE_PX = FAB_LIFT_PX + FAB_DIAMETER_PX + FAB_CONTENT_GAP_PX
