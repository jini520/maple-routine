/**
 * 넥슨이 스케줄러 기록을 결산 중인가. 우리 서버가 판정해 내려 준다.
 *
 * 계약의 원본은 서버 저장소와 이 앱이 나눠 갖는다. 한쪽만 바꾸면 타입 검사가 못 잡으므로
 * 필드를 더할 때 양쪽을 함께 볼 것.
 */
export interface Settlement {
  settling: boolean
  /**
   * 이번 결산이 시작된 ISO 시각. `settling` 이 참일 때만 값이 있다.
   *
   * **앱이 닫은 결산을 알아보는 열쇠다.** 이 값이 닫을 때 기억한 것과 같으면 줄을 안 세운다.
   */
  startedAt: string | null
}
