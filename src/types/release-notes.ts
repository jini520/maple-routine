// 릴리스 노트(ADR-119). 진실 원천은 `packages/core/src/data/release-notes.ts` 한 벌이고, 거기서 두 갈래로
// 나간다 — 앱 번들에 그대로 실려 개발 노트 화면이 과거 전체를 읽고, 배포 스크립트가 그 버전
// 하나만 뽑아 `latest.json` 의 `notes` 로 실어 업데이트 모달이 읽는다.
// 형식이 JSON 이 아니라 `.ts` 인 이유가 이 파일이다 — 항목 단위 표식이 오타로 조용히
// 무시되는 것을 컴파일이 막는다(ADR-119 결정 1).

/**
 * 항목의 성격. 축은 이 저장소가 이미 쓰는 이슈 접두사(`[기능]`·`[개선]`·`[버그]`)와 같다 —
 * 노트를 쓸 때 새로 분류할 필요가 없도록 그 이름을 그대로 승계한다.
 */
export type ReleaseNoteCategory = 'feature' | 'improvement' | 'fix'

export interface ReleaseNoteItem {
  /** 화면과 매니페스트 문자열 양쪽에 배지·머리표로 붙는다(ADR-119 결정 9). */
  category: ReleaseNoteCategory
  text: string
  /**
   * 이 항목이 OTA 로 나가지 않는 네이티브 변경인지 — 화면에 스토어 업데이트 필요 표식이 붙는다.
   *
   * **버전이 아니라 항목에 붙는다**(ADR-119 결정 3). 한 릴리스에 OTA 로 가는 변경과 스토어가
   * 필요한 변경이 섞이는 것이 정상인데, 버전 단위로 묶으면 "이 버전은 스토어 업데이트 필요"가
   * 되어 **OTA 로 이미 받을 수 있는 나머지 변경까지 못 받는 것처럼** 읽힌다.
   *
   * 매니페스트의 `minNativeVersion` 과는 다른 층이다 — 그쪽은 *"이 번들을 적용할 수 있는가"* 를
   * 판정하는 게이트이고, 이 표식은 *"이 항목이 지금 내 앱에 있는가"* 를 사람에게 설명하는 글이다.
   * 무엇이 네이티브 변경인지는 스크립트가 아니라 **사람이 판정해 붙인다**.
   */
  requiresStoreUpdate?: boolean
  /**
   * 이 항목이 설명하는 기능의 사용법 안내. 값이 있으면 목록에서 그 항목만 눌리고
   * `›` 가 붙는다.
   *
   * **본문이 아니라 id 다.** 안내의 원천은 기능 카탈로그(`packages/core/src/data/feature-guides.ts`)이고 노트는
   * 거기로 **링크만** 건다(결정 1 정정) — 같은 설명이 버전 축과 기능 축에 두 벌 있으면 반드시
   * 갈라진다. 그리고 본문을 여기 둘 수도 없다: 배포 스크립트가 이 파일을 **Node 에서 직접
   * import** 하는데(ADR-119 결정 1, `scripts/publish-live-update.mjs`), 안내가 들고 오는 `.webp`
   * import 를 Node 가 해석하지 못해 그 자리에서 배포가 죽는다.
   *
   * 그래서 이 참조는 **타입이 지켜 주지 못한다**(문자열일 뿐이다) — 미아 참조는
   * `packages/core/src/data/__tests__/feature-guides.test.ts` 가 막는다. 반대 방향(노트가 안 가리키는 안내)은
   * **정상이다**: 카탈로그가 원천이므로 옛 기능은 노트 없이 안내만 있는 것이 맞다.
   */
  guideId?: string
  /**
   * 안내 **안의 어느 마디**로 떨어질지. `guideId` 없이 홀로 있으면 뜻이 없다.
   *
   * 릴리스에서 바뀐 것은 보통 기능 전체가 아니라 그중 한 마디다 — 페이지 맨 위에 떨어뜨리면
   * 읽는 사람이 그 마디를 다시 찾아야 한다. 비워 두면 안내 첫머리로 간다.
   */
  guideSectionId?: string
}

export interface ReleaseNote {
  /** `x.y.z` — 네이티브 빌드 번호가 아니라 OTA 번들 버전(`package.json` version)이다(ADR-119 결정 2) */
  version: string
  /** `YYYY-MM-DD` */
  date: string
  items: ReleaseNoteItem[]
  /**
   * **업데이트 모달이 받기 전에 보여줄 핵심 목록 3~4줄**. 배포 스크립트가 이
   * 배열만 뽑아 `latest.json` 의 `highlights` 로 싣는다 — 모달에 실리는 것은 `items` 가 아니다.
   *
   * **`items` 에서 파생하지 않는다**(결정 3). 앞 N개를 자르거나 `category` 로 거르면 "핵심"을
   * 노트에 적은 순서와 분류가 정하게 되는데, 둘 다 중요도가 아니다. 그리고
   * `일부 버그 및 사용성 개선` 처럼 **여러 항목을 한 줄로 뭉치는 줄**은 어떤 파생 규칙으로도
   * 나오지 않는다 — 문장의 목적이 다르다(항목은 *"무엇이 바뀌었나"*, 이쪽은 *"받으면 무엇이
   * 생기나"*). 그래서 개수가 `items` 와 맞을 이유가 없다.
   *
   * 과거 버전에는 없다(이미 발행됐고 다시 매니페스트에 실리지 않는다). **앞으로 나갈 버전에는
   * 반드시 있어야 하고**, 없으면 배포가 중단된다(결정 8).
   */
  highlights?: string[]
}
