/**
 * **화면이 자기 벽지를 들고 다니는가**.
 *
 * ## 왜 이런 갈림이 생겼나
 *
 *  는 벽지를 **한 장**으로 깔았다(`AppShell` 의 첫 자식). 그러려면 그 위에 얹히는
 * 내비게이션 화면들이 **투명**해야 하고(`navigation-theme.ts`), 그것이 벽지 테마에서 화면 배경을
 * 비우는 이유였다.
 *
 * 그 투명 이 안드로이드에서 전환 중에 드러난다. 두 화면이 겹치는 동안 **위 화면 너머로 아래
 * 화면의 글자가 그대로 비친다**(실기기 2026-08-15, 혼테일: 기능 설명의 행들이 컨텐츠 관리
 * 방법의 목차와 포개져 읽힌다). 투명한 화면은 벽지만 비추는 것이 아니라 **그 아래 화면도** 비춘다.
 *
 * **iOS 에는 이 증상이 없다**(사용자 확인). 그래서 화면을 불투명하게 만들고 벽지를 화면마다 들려
 * 보낸다 를 두 플랫폼에 다 적용하지 않는다. iOS 에서는 전환 중에도 벽지가 **고정**돼 보이는
 * 지금 모습이 더 낫고, 그것을 깨뜨릴 이유가 없다(29 와 같은 판단: 한쪽에서만
 * 나는 문제를 양쪽 모습을 바꿔서 고치지 않는다).
 *
 * ## 대가
 *
 * 안드로이드에서는 벽지가 **화면과 함께 미끄러진다**(각 화면이 자기 것을 들고 있으므로). 고정된
 * 벽지 위로 화면만 지나가던 모습과 다르지만, 겹쳐 읽히는 글자를 없애는 값으로 받는다.
 *
 * ## 값이 하나여야 하는 이유
 *
 * 이 판정은 **두 곳이 함께 지켜야 성립한다**. 화면 배경을 불투명하게 칠하는 쪽
 * (`navigation-theme.ts`)과 벽지를 화면마다 그리는 쪽(`ScreenBackdrop`). 한쪽만 바뀌면 벽지가
 * 통째로 사라지거나(불투명한데 안 그림) 겹침이 그대로 남는다(투명한데 그림). 그래서 상수 하나를
 * 두 곳이 읽는다.
 */

