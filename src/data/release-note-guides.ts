//
// **OTA 는 dist 전체를 압축해 내려주므로 이미지가 곧 번들 용량이다**(지연 로드가 깎아 주지 않는다).
// 릴리스마다 누적되는 자산이라 한 장당·누적 상한을 정해 관리한다.
//
// 이 파일은 순수 데이터다 — `features/`·`storage/`·`native/` 를 import 하지 않는다.
//
// ---
