// **이미지는 `import.meta.glob` 이 아니라 명시적 import 다**(ADR-125 결정 4) — glob 조회는 파일명이
// 틀리면 `undefined` 를 돌려주고 이미지만 빠진 채 통과하지만, 명시적 import 는 **빌드가 실패한다.**
