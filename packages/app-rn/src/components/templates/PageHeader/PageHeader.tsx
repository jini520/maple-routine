import { View } from 'react-native'
import { useSafeAreaInsets } from 'react-native-safe-area-context'

import { ThemeHeaderBackdrop } from '../ThemeHeaderBackdrop/ThemeHeaderBackdrop'

// 화면 상단 헤더 셸([[ADR-094]] 4단계). 스케줄러 계열 4화면이 **글자 하나까지 같은** 마크업을
// 복붙하고 있었다 — 셸 클래스, 테마 배경 조각, 하단 페이드까지. 취약 구조를 한곳에 가두는 것이
// 목적이고([[ADR-094]] 결정 1), 그 취약함의 내용이 RN 에서 통째로 바뀐다.
//
// ══ 이 컴포넌트에서 가장 크게 갈린 것: **`fixed` 도 spacer 도 없다** ═══════════════════════
//
// 웹에서 이 헤더는 `fixed inset-x-0 top-0` + **실측 높이 spacer** 였다([[ADR-098]] 결정 2 ·
// [[ADR-085]] 결정 1). 그 형태가 필요했던 이유는 하나다 — 화면 전체가 문서 스크롤 하나를 공유하니
// 헤더도 그 안에 있었고, `sticky` 로 붙이면 **화면 위치가 스크롤 오프셋의 함수**가 되어 iOS 스크롤
// 스레드가 옛 오프셋을 뒤늦게 되돌려 보내는 프레임에 헤더가 화면 밖으로 날아갔다.
//
// RN 에는 그 사슬의 첫 고리가 없다. 화면은 문서가 아니고, 스크롤은 `ScrollView` 라는 **다른 뷰**가
// 소유한다([[ADR-099]] 가 웹에서 힘들여 만든 상태가 여기서는 기본값이다). 그래서 `fixed` 도
// spacer 도 옮길 자리가 없다.
//
// **한때 이 헤더는 스크롤 뷰의 «형제» 였다** — *"헤더는 스크롤과 무관하게 화면 위에 있다"* 를 RN
// 에서 표현하는 가장 곧은 방법이었고, 그러면 헤더 위치는 스크롤 오프셋의 함수이기는커녕 **함수가
// 아니었다.** [[ADR-131]] 이 그 성질을 **일부러 버렸다** — 화면에 고정되는 영역을 두지 않기로
// 하면서 헤더가 스크롤 뷰의 **첫 자식**이 됐다(`ScreenScroll`). 헤더 위치는 이제 오프셋의 함수다.
//
// **그래도 [[ADR-085]] 결정 1 의 사고는 돌아오지 않는다.** 그 결함은 `sticky` 가 «오프셋 → 화면
// 위치» 를 **매 프레임 다시 계산**하는데 iOS 스크롤 스레드가 옛 오프셋을 뒤늦게 돌려보내면서 났다.
// 지금 헤더는 계산 대상이 아니라 **그냥 콘텐츠**라, 오프셋이 어떤 값으로 돌아오든 콘텐츠와 **같이**
// 움직인다 — 어긋날 두 값이 없다.
//
// 딸려서 사라지는 것 셋:
//
// ① **spacer 가 없다.** 그것은 `fixed` 가 헤더를 흐름에서 빼기 때문에 필요했던 자리다. 헤더가
//    흐름 안에 있으면 뺄 자리가 없다.
// ② **실측(`useMeasuredHeight`)이 없다.** spacer 가 없으니 맞출 대상이 없다. [[ADR-112]] 가 이슈
//    #168 에서 잡은 결함(*"헤더는 이미 짧은데 spacer 는 옛 값인 프레임"*)은 여기서 **구조적으로
//    불가능**하다 — 헤더와 그 아래 스크롤 뷰가 같은 레이아웃 패스에서 배치되므로 서로 어긋난
//    프레임이라는 것이 존재하지 않는다. 그 ADR 이 지키려던 계약을 코드가 아니라 구조가 만족한다.
//    (`useLayoutEffect` 로 재던 이유도 함께 사라진다 — RN 의 `onLayout` 은 레이아웃 **뒤**에 오는
//    비동기 통보라 애초에 그 계약을 만족시킬 수 없었다. 그래서 웹 형태를 그대로 옮기는 쪽이
//    오히려 [[ADR-085]] 결정 1 이 금지한 "첫 프레임에 spacer 0" 을 되살렸을 것이다.)
// ③ **콘텐츠가 헤더 밑으로 지나가지 않는다.** 웹은 불투명 헤더 아래로 카드가 흘러 들어갔는데,
//    여기서는 헤더가 흐름의 맨 앞이라 뒤 카드가 밀려날 뿐 겹칠 일이 없다. **보이는 모습은 같다** —
//    헤더가 불투명했으므로 밑으로 들어간 것은 어차피 안 보였다.
//
//    다만 [[ADR-131]] 뒤로 **상태바 밑은 지나간다.** 헤더가 올라가면 그 자리에 아무 배경이 없다.
//    고정을 없앤 대가로 그 ADR 이 «남는 문제» 에 적어 뒀고, 처방은 아직 안 골랐다.
//
// 대신 **하나가 새로 생긴다: 그리는 순서.** 헤더는 흐름의 **맨 앞**이라 기본 순서로는 뒤에 오는
// 형제(목록)가 위에 그려진다. 그래서 `z-10` 을 준다 — 웹에도 있던 그 클래스가 여기서는 "목록 위에
// 그린다"가 아니라 **"헤더의 삐져나온 자식(페이드·당김 인디케이터)이 목록 위에 그려진다"** 를
// 뜻한다. 스크롤 뷰의 형제였을 때와 자식일 때가 **같은 이유로 같은 값**이다.
//
// ── 안전영역 ─────────────────────────────────────────────────────────────────────
//
// `pt-[calc(1rem+var(--sa-top))]` → `paddingTop: insets.top + 16`. 값의 출처가 CSS 변수 주입에서
// `SafeAreaProvider` 로 바뀔 뿐 뜻은 같다(그래서 `SystemBarsPort.refreshSafeAreaInsets()` 가 RN 에서
// 할 일이 없다 — `native/adapters/rn-system-bars.ts`). **헤더가 상단 안전영역을 먹는 쪽이라는
// 사실이 계약이다** — `ScreenScroll` 은 헤더가 있으면 그 위쪽을 건드리지 않는다.
//
// ── 보스 수익은 여전히 여기 포함하지 않는다 ────────────────────────────────────────
//
// 같은 형태지만 페이지 헤더에 경계 페이드를 두지 않는다([[ADR-047]] 결정 6). 헤드라인 실측을 중첩
// sticky 레일에 쓰던 **쓰임 쪽이 없어졌다** — [[ADR-131]] 이 그 레일과 `stickyTop` 오프셋
// ([[ADR-047]] 결정 3 · [[ADR-100]] 결정 3)을 통째로 폐기했다. 남는 이유는 «페이드가 없다» 하나다.

export interface PageHeaderProps {
  /** 헤더 내용. 안에서 `gap-4` 로 세로 간격이 잡힌다(웹 `space-y-4` 의 짝). */
  children: React.ReactNode
  /**
   * 헤더 **바로 아래 띠**(`top-full`)에 겹쳐 그릴 것 — 현재는 당겨서 새로고침 인디케이터
   * 하나다(스케줄러 2화면).
   *
   * 프롭으로 받는 이유는 웹과 같다 — 그 인디케이터는 `absolute inset-x-0 top-full` 이라 **이 셸이
   * 기준 상자여야** 한다. `children` 에 섞으면 `gap-4` 안으로 들어가 흐름 자식이 되어 위치가
   * 완전히 달라진다.
   */
  below?: React.ReactNode
}

/** `pt-[calc(1rem+var(--sa-top))]` 의 상수 몫. */
const HEADER_TOP_PADDING_PX = 16

export function PageHeader(props: PageHeaderProps): React.JSX.Element {
  const insets = useSafeAreaInsets()

  return (
    <View
      testID="page-header"
      className="z-10 bg-bg px-4 pb-2"
      style={{ paddingTop: insets.top + HEADER_TOP_PADDING_PX }}
    >
      {/* [[ADR-088]] 결정 5-1: 헤더 자리의 테마 배경 조각(배경 없는 테마에선 렌더 안 됨).
          **첫 자식이어야 한다** — RN 은 형제 순서가 곧 그리는 순서라, 이 자리가 웹의
          `z-index: -1`(헤더 배경 위·콘텐츠 아래)을 대신한다. */}
      <ThemeHeaderBackdrop />

      <View className="gap-4">{props.children}</View>

      {/* **경계 페이드를 걷어냈다**(2026-08-13, 사용자 판정 — 실기기에서 «띠가 엉뚱한 자리에
          있다», 제거 승인).

          웹에서 이 띠는 헤더 아래 32px 에 겹쳐 그려 목록이 경계에서 딱 끊기지 않게 하는 것이었다.
          RN 에서 그 자리를 `absolute … top-full h-8` 로 옮겼는데, 그 배치는 **부모(헤더) 높이를
          기준으로 100% 아래**를 뜻하므로 헤더가 스크롤에 맞춰 높이를 바꾸는 자리에서는 띠가 함께
          움직여 의도한 경계와 어긋난다.

          위치를 고치는 대신 없앤 이유: 이 띠는 [[ADR-047]] 결정 6 이 **페이지 헤더에는 두지
          않기로** 한 것과 같은 부류의 장식이고([[ADR-123]] 이 블러를 걷어낸 것도 같은 방향),
          지금은 [[ADR-047]] 의 중첩 sticky 자체가 RN 에 없어 이 띠가 덮어 줄 경계도 없다.
          **되살릴 조건이던 «sticky 를 먼저 세운다» 는 영영 성립하지 않는다** — [[ADR-131]] 이
          화면에 고정되는 영역을 두지 않기로 정했고, 헤더까지 함께 스크롤되면 «헤더 아래로
          콘텐츠가 지나가는 경계» 자체가 없다. 조건부 보류가 아니라 확정 폐기다.

          되살릴 때 필요한 값(알파 **(1−t)²** 프로파일 · 정지점이 전부 테마 `bg` 의 알파 변주 ·
          블러 금지 [[ADR-123]])은 **웹 원본**(`app-capacitor` 의 같은 헤더)에 그대로 있다. 여기
          상수로 남겨 두지 않는 이유는 쓰는 데가 없는 값이 lint 를 깨고, 그 상태로 두면 다음
          사람이 "왜 있는데 안 쓰지"를 먼저 풀어야 하기 때문이다. */}

      {props.below}
    </View>
  )
}
